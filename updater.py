#!/usr/bin/env python3
"""Release helper for the CAS.AI Kotlin Multiplatform plugin.

Edit the two versions below, then run the script. Everything else derives from them:
`gradle/libs.versions.toml` is the single source of truth, `iosApp/Podfile` reads the CAS version
from it at `pod install` time, and the podspecs are generated by Gradle.

    python3 updater.py            apply the versions and regenerate the podspecs
    python3 updater.py check      fail if the generated files drifted, for CI
    python3 updater.py publish    upload a deployment and leave it for a manual release
    python3 updater.py publish --local    publish to build/repo instead, to inspect it first

Raising CAS_VERSION also moves the CAS Gradle plugin to that version, so it has to exist on Maven
Central before the podspecs can be regenerated.

Credentials
-----------

They go into `local.properties`, the same file that already holds `sdk.dir`. Git ignores it, as it
does any `*.gpg` key beside it, and neither must ever be committed.

    # User token of the Central portal account, from https://central.sonatype.com/account
    mavenCentralUsername=
    mavenCentralPassword=

    # Signing, a keyring file as produced by `gpg --export-secret-keys`
    signing.keyId=<last 8 characters of the key id>
    signing.password=<passphrase>
    signing.secretKeyRingFile=/absolute/path/to/key.gpg

The `com.cleveradssolutions` namespace is already verified for that account. An in-memory key works
too, for CI where the value comes from a secret: `signingInMemoryKey` and
`signingInMemoryKeyPassword` instead of the three `signing.*` keys. An incomplete pair counts as no
key at all, so publishing to the local repository keeps working while credentials are missing.

Gradle reads `ORG_GRADLE_PROJECT_<name>` as a project property, and that is how this script hands
the credentials over, so they never appear in the process arguments. On CI, set those variables
directly and leave `local.properties` out of the checkout.

Maven Central only accepts signed artifacts, so check that `build/repo` carries the `*.asc` files
before uploading. The upload waits until Central has validated the deployment and stops there:
releasing stays a manual step at https://central.sonatype.com/publishing/deployments.

Checklist
---------

1. Edit CAS_VERSION and PLUGIN_VERSION, run `python3 updater.py`.
2. Build both samples: `./gradlew :cas-kmp:build :cas-demo-app:assembleDebug`, then `pod install`
   in `iosApp` and build the `iosApp` scheme in Xcode.
3. Commit, tag with the plugin version, push.
4. `python3 updater.py publish`, then release the deployment in the portal.
5. Write the release notes in the GitHub release for the tag.
6. Update `versions.kmp` in the documentation, https://github.com/cleveradssolutions/docs.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

# ---------------------------------------------------------------------------
# Versions
# ---------------------------------------------------------------------------

# CAS.AI SDK, used by the Android dependencies, the CAS Gradle plugin and the iOS pods.
CAS_VERSION = "4.8.0"

# Published version of this library.
PLUGIN_VERSION = "4.8.0"

# ---------------------------------------------------------------------------

ROOT = Path(__file__).resolve().parent
CATALOG = ROOT / "gradle" / "libs.versions.toml"
LOCAL_PROPERTIES = ROOT / "local.properties"
PODSPECS = (ROOT / "cas-kmp" / "cas_kmp.podspec",)

VERSION_RE = re.compile(r"^\d+\.\d+\.\d+(?:[-.][0-9A-Za-z.-]+)?$")
CREDENTIAL_KEYS = ("mavenCentralUsername", "mavenCentralPassword", "signing.")


def read(key: str) -> str:
    match = re.search(rf'^{re.escape(key)}\s*=\s*"([^"]+)"', CATALOG.read_text(), re.MULTILINE)
    if match is None:
        sys.exit(f"error: `{key}` not found in {CATALOG.relative_to(ROOT)}")
    return match.group(1)


def write(key: str, value: str) -> bool:
    if not VERSION_RE.match(value):
        sys.exit(f"error: `{value}` is not a valid version for `{key}`")
    text = CATALOG.read_text()
    new_text, count = re.subn(
        rf'^({re.escape(key)}\s*=\s*)"[^"]+"',
        lambda m: f'{m.group(1)}"{value}"',
        text,
        count=1,
        flags=re.MULTILINE,
    )
    if count != 1:
        sys.exit(f"error: `{key}` not found in {CATALOG.relative_to(ROOT)}")
    if new_text == text:
        return False
    CATALOG.write_text(new_text)
    return True


def gradle(*tasks: str, env_extra: dict[str, str] | None = None) -> None:
    import os

    env = dict(os.environ)
    if env_extra:
        env.update(env_extra)
    result = subprocess.run([str(ROOT / "gradlew"), "-p", str(ROOT), *tasks], env=env)
    if result.returncode != 0:
        sys.exit(result.returncode)


def credentials_env() -> dict[str, str]:
    """Gradle reads ORG_GRADLE_PROJECT_<name> as a project property.

    The publishing plugin resolves the Maven Central credentials before the project is configured,
    so a properties file cannot reach it; the environment can.
    """
    if not LOCAL_PROPERTIES.exists():
        sys.exit(f"error: {LOCAL_PROPERTIES.name} is missing, see the README for the keys it needs")

    env: dict[str, str] = {}
    for line in LOCAL_PROPERTIES.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        if key.startswith(CREDENTIAL_KEYS):
            env[f"ORG_GRADLE_PROJECT_{key}"] = value.strip()

    missing = [k for k in ("mavenCentralUsername", "mavenCentralPassword")
               if f"ORG_GRADLE_PROJECT_{k}" not in env]
    if missing:
        sys.exit(f"error: {LOCAL_PROPERTIES.name} has no {', '.join(missing)}")
    return env


def apply_versions() -> int:
    changed = write("cas", CAS_VERSION) | write("casKmp", PLUGIN_VERSION)
    print(f"CAS.AI SDK  cas     = {read('cas')}")
    print(f"Plugin      casKmp  = {read('casKmp')}")
    if not changed:
        print("\nAlready up to date.")
        return 0
    print("\nRegenerating the podspecs...")
    gradle("--quiet", ":cas-kmp:podspec", ":cas-demo-app:podspec")
    print("Done. Review the changes, then commit and tag the release.")
    return 0


def check() -> int:
    cas, plugin = read("cas"), read("casKmp")
    problems = []
    if cas != CAS_VERSION:
        problems.append(f"gradle/libs.versions.toml: cas is {cas}, this script says {CAS_VERSION}")
    if plugin != PLUGIN_VERSION:
        problems.append(f"gradle/libs.versions.toml: casKmp is {plugin}, this script says {PLUGIN_VERSION}")
    for podspec in PODSPECS:
        text = podspec.read_text()
        name = podspec.relative_to(ROOT)
        version = re.search(r"spec\.version\s*=\s*'([^']+)'", text)
        if version and version.group(1) != plugin:
            problems.append(f"{name}: spec.version is {version.group(1)}, expected {plugin}")
        dependency = re.search(r"spec\.dependency 'CleverAdsSolutions-Base', '([^']+)'", text)
        if dependency and dependency.group(1) != cas:
            problems.append(f"{name}: CleverAdsSolutions-Base is {dependency.group(1)}, expected {cas}")

    if problems:
        print("Out of sync:")
        for problem in problems:
            print(f"  {problem}")
        print("\nRun `python3 updater.py` to bring everything in line.")
        return 1
    print(f"In sync. CAS.AI SDK {cas}, plugin {plugin}.")
    return 0


def publish(local: bool) -> int:
    if local:
        print("Publishing to build/repo")
        gradle(":cas-kmp:publishAllPublicationsToLocalBuildRepository", env_extra=credentials_env())
        print("\nDone. Inspect build/repo, the signatures are the *.asc files.")
        return 0

    print("Uploading a deployment to Maven Central")
    gradle(":cas-kmp:publishToMavenCentral", env_extra=credentials_env())
    print(
        "\nThe deployment was uploaded and is waiting for a manual release.\n"
        "Review it at https://central.sonatype.com/publishing/deployments and publish it from there."
    )
    return 0


def main() -> int:
    args = sys.argv[1:]
    command = args[0] if args else "apply"

    if command == "apply":
        return apply_versions()
    if command == "check":
        return check()
    if command == "publish":
        return publish(local="--local" in args)

    print(__doc__)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
